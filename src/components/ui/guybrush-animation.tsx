/* Use frames 1,2,3,4 then reverse 3,2 for a smooth spyglass cycle */
const FRAMES = [F1, F2, F3, F4, F3, F2];

/**
 * GuybrushWalkingBG — Guybrush walks across the footer from right to left,
 * cycling through the spyglass animation frames provided by the user.
 */
export function GuybrushWalkingBG() {
  const canvasRef = useRef<HTMLCanvasElement>(null);

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext("2d");
    if (!ctx) return;

    const pixelSize = 2;
    const spriteW = COLS * pixelSize;
    const spriteH = ROWS * pixelSize;

    const parent = canvas.parentElement;
    if (!parent) return;

    const resizeCanvas = () => {
      canvas.width = parent.clientWidth;
      canvas.height = spriteH + 10;
    };
    resizeCanvas();
    window.addEventListener("resize", resizeCanvas);

    let posX = canvas.width + 20;
    let frameIdx = 0;
    let tickCount = 0;
    let animId: number;

    const renderFrame = (data: number[]) => {
      for (let r = 0; r < ROWS; r++) {
        for (let c = 0; c < COLS; c++) {
          const val = data[r * COLS + c];
          if (val > 0 && PALETTE[val]) {
            ctx.fillStyle = PALETTE[val];
            ctx.fillRect(
              posX + c * pixelSize,
              5 + r * pixelSize,
              pixelSize,
              pixelSize
            );
          }
        }
      }
    };

    const loop = () => {
      ctx.clearRect(0, 0, canvas.width, canvas.height);

      tickCount++;
      if (tickCount % 10 === 0) {
        frameIdx = (frameIdx + 1) % FRAMES.length;
      }

      renderFrame(FRAMES[frameIdx]);

      posX -= 0.8;

      if (posX < -spriteW - 20) {
        posX = canvas.width + 20;
      }

      animId = requestAnimationFrame(loop);
    };

    animId = requestAnimationFrame(loop);

    return () => {
      cancelAnimationFrame(animId);
      window.removeEventListener("resize", resizeCanvas);
    };
  }, []);

  return (
    <div className="pointer-events-none absolute bottom-0 left-0 right-0 overflow-hidden opacity-30">
      <canvas
        ref={canvasRef}
        className="block w-full"
        style={{ imageRendering: "pixelated" }}
      />
    </div>
  );
}

